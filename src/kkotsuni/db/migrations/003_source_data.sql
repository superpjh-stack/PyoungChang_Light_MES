CREATE TABLE source_file (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 digest TEXT NOT NULL UNIQUE, filename TEXT NOT NULL, kind TEXT NOT NULL,
 content BYTEA NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE source_record (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 file_id BIGINT NOT NULL REFERENCES source_file(id), sheet TEXT NOT NULL, row_number INTEGER NOT NULL,
 kind TEXT NOT NULL, payload JSONB NOT NULL, status TEXT NOT NULL DEFAULT '검토 필요',
 issue TEXT, order_no TEXT REFERENCES order_hdr(order_no),
 product_code TEXT REFERENCES product(product_code),
 UNIQUE(file_id,sheet,row_number)
);
CREATE TABLE source_identity (
 identity TEXT PRIMARY KEY, record_id BIGINT NOT NULL REFERENCES source_record(id)
);
CREATE INDEX source_record_order ON source_record(order_no);
ALTER TABLE product ADD COLUMN tax_review_required BOOLEAN NOT NULL DEFAULT FALSE;
